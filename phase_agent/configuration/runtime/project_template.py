def write_project_entry(root):
    root = Path(root)
    application = Path(__file__).resolve().parents[3]
    content = (
        "# Generated by phase_agent: project entry v1\n"
        "from pathlib import Path\nimport subprocess\nimport sys\n\n"
        f"APPLICATION = Path({str(application)!r})\n"
        f"PYTHON = Path({sys.executable!r})\n\n"
        'if __name__ == "__main__":\n'
        '    config = Path(__file__).resolve().with_name("agent_runtime.json")\n'
        '    if not PYTHON.is_file() or not (APPLICATION / "phase_agent").is_dir():\n'
        '        print("Runtime location unavailable; open the current project launcher to repair the entry.")\n'
        "        raise SystemExit(2)\n"
        '    command = [str(PYTHON), "-m", "phase_agent.runtime.local_project_launcher",\n'
        '               "--project", str(config), *sys.argv[1:]]\n'
        "    raise SystemExit(subprocess.call(command, cwd=APPLICATION))\n"
    )
    compile(content, "run_project.py", "exec")
    target = root / "run_project.py"
    if target.exists():
        if target.read_text(encoding="utf-8") != content:
            raise FileExistsError(f"Existing project entry differs; preserved: {target}")
        return target
    with target.open("x", encoding="utf-8", newline="\n") as stream:
        stream.write(content)
    return target



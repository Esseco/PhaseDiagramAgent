"""Recommendation and action contract for layered-oxide NEPkit initialization."""
from __future__ import annotations
from collections.abc import Mapping


def recommend_nepkit_initialization(system: Mapping, boundary: Mapping) -> dict:
    """Recommend broad, small initial coverage after boundary definition."""
    system_id = str((system or {}).get("system_id", "")).lower()
    phases = list((boundary or {}).get("P") or (boundary or {}).get("phases") or [])
    tm_ratio = (boundary or {}).get("TM_ratio") or (boundary or {}).get("tm_ratios") or {}
    elements = set(tm_ratio) | {str(x) for x in (boundary or {}).get("elements", [])}
    layered = "layer" in system_id or "oxide" in system_id or bool(phases)
    complex_system = len(elements) >= 3 or len(phases) > 1 or bool((boundary or {}).get("SOC"))
    recommended = layered and complex_system
    return {
        "recommended": recommended,
        "reason": "复杂多元层氧体系适合少量跨相/跨组成广覆盖初始化" if recommended else "当前体系可继续使用现有初始化流程",
        "coverage": "broad_small",
        "selection_axes": ["phase", "SOC", "Na_content", "supercell_det"],
        "count_policy": "reuse existing initial_states_per_branch and region quotas; no fixed scientific count",
        "requires_confirmation": True,
    }


def validate_nepkit_initialization(parameters: Mapping) -> dict:
    required = {"initial_structures", "boundary", "confirmed"}
    missing = sorted(required - parameters.keys())
    if missing:
        raise ValueError(f"missing layered-oxide initialization fields: {missing}")
    if parameters["confirmed"] is not True:
        raise ValueError("NEPkit initialization requires explicit confirmation")
    if not isinstance(parameters["initial_structures"], list) or not parameters["initial_structures"]:
        raise ValueError("initial_structures must be a non-empty list generated by the phase agent")
    if not isinstance(parameters["boundary"], Mapping):
        raise TypeError("boundary must be a mapping")
    if int(parameters.get("max_det_H", 6)) != 6:
        raise ValueError("layered-oxide initialization requires max_det_H=6")
    if int(parameters.get("frames_per_parent", 36)) != 36:
        raise ValueError("frames_per_parent must be 36")
    return {
        "action_type": "prepare_nepkit_initial_dataset",
        "initial_structures": list(parameters["initial_structures"]),
        "boundary": dict(parameters["boundary"]), "confirmed": True,
        "max_det_H": 6, "frames_per_parent": 36,
        "direct_samples": int(parameters.get("direct_samples", 100)),
        "relax_fmax": float(parameters.get("relax_fmax", 0.1)),
        "local_sampler": "Process_MLIP.perturb_layered_oxide_structure",
        "coverage": "broad_small",
        "remote_stages": ["relax", "geometry_filter", "m3gnet_features", "direct_sampling", "dft", "finetune", "qbc"],
    }


def prepare_nepkit_initial_dataset(*, action, context=None):
    payload = validate_nepkit_initialization(action.get("parameters") or {})
    return {"status": "not_configured", "action_type": payload["action_type"], "parameters": payload,
            "reason": "NEPkit当前仅有参数契约；微扰生成、MH-1弛豫及后续计算尚未接入此Agent入口。",
            "requires_local_perturbation": True, "requires_upload": True,
            "requires_remote_execution": True, "submitted": False}
